                                 <h3>INTRODUCTION</h3> 
                             <p>SME ELECTRONIC PRODUCTS EXPORT PROMOTION COUNCIL is initiated to provide an exclusive support to the SME Sector for the promotion of exports and other business activities. Indian SMEs have limited resource and support to identify emerging business opportunities from international markets. They are also facing problems to get export orders because of lack of information, contacts, negotiation skills, knowledge about potential markets, insufficient funds and lack of support from the various Government agencies. The Council has connectivity in various countries for the promotion of SMEs business and to identify potential markets for their quality products.</p>
                                
                                <p><b>The Council is founded by Mr. Chandrakant Salunkhe, President, SME Chamber of India (Small and Medium Business Development Chamber of India) and SME Export Promotion Council for enhancing the business growth of SMEs and to develop trade with untapped markets. Mr. Salunkhe observed that many Small and Medium Entrepreneurs are not capable to enter into international markets of their own, even though they have quality products and services.</b></p>
                                
                              
                               <p>The Council offers a range of services designed to accelerate exports for its members, market research and studies in key international markets, and facilitates participation in global trade shows, conferences, and exhibitions to promote India's electronics, software, and IT sectors. To enhance the brand equity of Indian IT, publicity campaigns and created exclusive India pavilions at the major trade shows.</p>
                        
                         <p>The Council also fosters business connections by organising buyer-seller meets, managing business missions, and providing matchmaking and contract promotion services. Additionally, it sends trade inquiries and global tenders related to the electronics and IT to its members. </p>

