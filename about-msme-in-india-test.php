                                affecting SMEs as well as the coverage and investment ceiling of the sector.
                                The Act seeks to facilitate the development of these enterprises as also enhancing
                                their competitiveness. It provides the first-ever legal framework for recognition
                                of the concept of "enterprise" which comprises both manufacturing and service 
                                entities. It defines medium enterprises for the first time and seeks to integrate 
                                the three tiers of these enterprises, namely, micro, small and medium. The Act also
