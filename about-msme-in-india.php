              <p>Micro, Small and Medium Enterprise (MSME) sector has emerged as a very important sector of the Indian economy, contributing significantly to the employment generation, innovation, exports, and inclusive growth of the economy. Micro, Small and Medium Enterprises (MSME) are the backbone of the socio-economic development of our country. It also accounts for 45 % of total industrial production, 40% of total exports and contributes very significantly to the GDP. Manufacturing segment within the MSME contributes to 7.09% of GDP. MSMEs also contribute to 30.50% of services. The total contribution of MSMEs to the GDP is 37.54.</p><br>
              <p>The MSME Act, 2006, was enacted to provide enabling policy environment for promotion and development of the sector by way of defining MSMEs, putting in place a framework for developing and enhancing competitiveness of the MSME enterprises, ensuring flow of credit to the sector and paving the way for preference in Government procurement to products and services of the MSEs, address the issue of delayed payments, etc. It is expected that the new law will be able to address the major challenges, relating to physical infrastructural bottlenecks, absence of formalization, technology adoption, capacity building, backward and forward linkages, lack of access to credit, risk capital, perennial problem of delayed payments, etc. These problems are hindering the development of a conducive business environment for expansion of the sector. The Ministry of MSME noted that a thriving entrepreneurial eco-system is a policy imperative for realizing the potential of the sector and ensuring sustainable growth of the sector.</p><br>
              <p>Global trends in classifying the MSMEs show that they widely differs across jurisdictions and depends upon the Government policies of the country. Though, a comparison of some of the countries revealed that most of them are using number of employees as a variable to define MSMEs, in India, MSMEs are presently defined based on investment in plant and machinery / equipment. </p>
