                                                        <!--<p style="margin-left: 50px;">for the period of 2019 – 2022 </p>-->
                                                        <p style="text-align: justify; margin-bottom: 10px;">
                                                            <b>National Advisory Board</b> has been providing valuable inputs, suggestions and recommendations for the empowerment of SMEs, accomplishing objectives of SME Chamber of India and its initiatives. The Board is providing unique guidance for organising various activities for enhancement of knowledge & skill of SMEs, Stat-Ups, Young & Women Entrepreneurs for better business growth.    
                                                        </p>
                                                        <p style="text-align: justify; margin-bottom: 10px;">
                                                            This Council has been also reviewing various issues, problems, hurdles, trends, difficulties related to   policies, schemes, incentives, acts  & regulations which is affecting to SME sector.   The Board will recommend to various Departments & Agencies of  Union Ministries & State Governments, Regulatory Bodies, Government PSUs, Corporations, Financial Institutions, Rating Agencies, State’s Industrial Development Corporations and other Stake Holders to Change Policy, unique Implementation Strategy for strengthening and creating confidence amongst SME sector as well as prepare level playing  field to compete with Local & Global Markets. The members of the Board will act as the Mentor and Philosopher to transform Chambers activities for the benefits of SME Sector.
                                                        </p>
                                                        <p style="text-align: justify; margin-bottom: 10px;">       
                                                            The Board will also advise to explore emerging business opportunities for SMEs related to export market, joint venture, technology transfer, contract manufacturing, tie-ups, distributorship, franchise, channelizing adequate & affordable bank finance, trade finance, foreign investment, international collaborations, procurement & supply to large corporate, Government PSUs, listing in SME Stock Exchange, new Entrepreneurship, empowerment of Young & Women Entrepreneurs, executive educational program for skill & scale development and various other activities & programs for the growth of SMEs.
                                                        </p>
                                                        <p style="text-align: justify; margin-bottom: 10px;">
                                                            The members of Board will periodically interact with Ministers, Government Officials, Heads of Regulatory Bodies, Heads of Government Agencies, Diplomats, Senior Executives of Corporate, MNCs, Financial Institutions, International Organisations, Rating Agencies, Media, Technocrats, Experts, inventors, scientists, business tycoons and other appropriate authorities.
                                                        </p>
