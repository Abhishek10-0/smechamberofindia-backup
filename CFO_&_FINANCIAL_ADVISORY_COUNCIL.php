                        <p>
                          Prof. Suresh D. Tendulkar, Chairman, Indian SME Knowledge Forum; Director, Central Board of RBI; and Former Chairman, Economic Advisory Council to the Prime Minister, launched the CFO & Financial Advisory Council for SMEs, initiated by SME Chamber of India, along with other dignitaries (left to right) in the picture: Mr. Chaitanya Shah, CEO, CKPP Associates, Mr. Chandrakant Salunkhe, President, SME Chamber of India; Mr. K.R. Sharma, Director, MSME Development Institute, Maharashtra; and Mr. Ravi Shankar, Founder Director, Brickwork Ratings India Pvt. Ltd.
