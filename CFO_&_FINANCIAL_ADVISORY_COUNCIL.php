                      <h3>ABOUT</h3> 
                        <p>
                          Small and Medium Enterprises contribute significantly to industrial output, exports, and employment generation and the nation’s economic growth. Finance remains one of the major concerns for SMEs. Many entrepreneurs are technically sound but lack  knowledge and the presentation of financial matters.
                        </p>
                        <p>
                          An entrepreneur has to play multiple roles in managing their business right from planning, purchasing, design, production, quality control, marketing, finance, manpower, public relations, new business development, and targeted growth. Due to their small size, they cannot afford to appoint highly qualified full-time finance executives to manage their finances, interact with bankers and regulatory agencies, as well as comply with statutory requirements.
                        </p>
                        <p>
                          With a view to providing efficient and cost-effective financial management solutions, the Small & Medium Business Development Chamber of India (SME Chamber of India), Maharashtra Industry Development Association, India International Trade Centre (IITCINDIA), and SME Business Management Institute have initiated a division called <b>“CFO and Financial Advisory Council for SMEs”</b>.
                        </p>
                        
                        <p>
                          This Council consists of a full-time team of financial experts to provide appropriate advice and assistance to SMEs on-call or on a regular basis by appointing a panel of members, partners, associates, consultants, and advisors—such as ex-bankers, retired government officials, CFOs, CAs, Company Secretaries, and other experts.
                        </p>
