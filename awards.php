                            <h2>India SME Excellence Awards</h2>

                            <p style="text-align: justify">
                               SME Chamber of India has been recognizing Small and Medium Enterprises and Entrepreneurs by conferring “INDIA SME EXCELLENCE AWARDS” for the last 24 years for their remarkable achievements & outstanding contributions, unique vision & mission for better & further business growth, enhancing profitability, strategic plans to achieve success in the local & global competitive markets, adoption of good governance & business ethics, fair business practices, better financial and business management strategies to improve credibility & creditworthiness to attract more business leads, channelise investments for further growth, collaborations with the Indian & foreign companies, unique concept for branding & marketing to attract more customers as well as clients. 

                               </p>
                              <br/> <p style="text-align: justify;">The Awards selection criteria also focuses on the improvement of quality productivity, industrial automation, innovations, inventions & its commercialisation, diversification,  expansion, transformation of the businesses to become emerging enterprises, generation of employment, new entrepreneurship, research & new product developments, acquiring of advanced & patented technologies to enhance global compositeness,  converting unique business ideas & concepts into business leads & growth, establishing co-operation with the Indian and foreign enterprises for the joint ventures, technology transfers, contract manufacturing and strategic alliances to enhance manufacturing activities.  </p>

                              <br/> <p style="text-align: justify;">The Chamber is also recognising the corporates, financial institutions (Public sector, private, foreign, co-operative & multi-state banks and NBFCs), multinational companies, educational institutions research and development agencies, Government corporations and agencies for the empowerment and strengthening of SME sector for better business growth and expansion/diversification.</p>
                              <br/> <p style="text-align: justify;">The award winners will be recognized as the “Business Ambassadors” to encourage other SMEs, entrepreneurs, Young & Women Entrepreneurs and start-ups to follow their success path for further growth & achievements and adoption of their unique ideas & efforts for the enhancement of business activities for more profitable.</p>
